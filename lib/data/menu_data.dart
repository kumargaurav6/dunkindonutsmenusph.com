// ---------------- Query helpers ----------------

MenuCategory categoryById(String id) {
  return categories.firstWhere(
    (c) => c.id == id,
    orElse: () => categories.first,
  );
}

List<MenuItem> itemsInCategory(String categoryId) {
  return items.where((i) => i.categoryId == categoryId).toList();
}

List<MenuItem> popularItems() {
  return items.where((i) => i.isPopular).toList();
}

List<MenuItem> searchItems(String query) {
  final q = query.trim().toLowerCase();
  if (q.isEmpty) return const [];
  return items.where((i) {
    final haystack =
        '${i.name} ${i.description} ${i.tags.join(' ')}'.toLowerCase();
    return haystack.contains(q);
  }).toList();
}
